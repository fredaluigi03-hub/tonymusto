export const localizeServices = (lang: Lang): ServiceItem[] =>
  servicesData.map(service => ({
    ...service,
    ...servicesStrings[lang].items[service.id as keyof typeof servicesStrings.it.items],
  }));

export const useServices = (): ServiceItem[] => {
  const { lang } = useLang();
  return useMemo(() => localizeServices(lang), [lang]);
};
